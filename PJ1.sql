--DATE TABLE
CREATE TABLE DIM_DATE(
DATE_ID INT IDENTITY(1,1) PRIMARY KEY,
FULL_DATE DATE,
YEAR INT,
MONTH INT,
MONTH_NAME VARCHAR(25),
QUARTER INT,
DAY INT,
WEEK INT
)

