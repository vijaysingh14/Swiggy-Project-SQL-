--KPI'S
--TOTAL ORDERS
SELECT COUNT(ORDER_ID) AS TOTAL_ORDERS FROM FACT_SWIGGY_ORDERS

--TOTAL REVENUE (INR MILLION)
SELECT FORMAT(SUM(CONVERT(FLOAT,PRICE_INR))/1000000,'N2') + ' INR MILLION' AS TOTAL_REVENUE FROM FACT_SWIGGY_ORDERS

----AVERAGE DISH PRICE
SELECT FORMAT(AVG(CONVERT(FLOAT,PRICE_INR)),'N2') + ' INR ' AS AVG_DISH_PRICE FROM FACT_SWIGGY_ORDERS

--AVERAGE RATING
SELECT FORMAT(AVG(CONVERT(FLOAT,RATING)),'N2') AS AVERAGE_RATING FROM FACT_SWIGGY_ORDERS

--DATE-BASED ANALYSIS
--MONTHLY ORDER TRENDS

SELECT D.YEAR,D.MONTH,D.MONTH_NAME,COUNT(*) AS MONTHLY_ORDER_TRENDS FROM FACT_SWIGGY_ORDERS F
JOIN DIM_DATE D ON D.DATE_ID=F.DATE_ID GROUP BY D.YEAR,D.MONTH,D.MONTH_NAME ORDER BY COUNT(*) DESC

--SUM OF SALES BASED ON MONTH
SELECT D.YEAR,D.MONTH,D.MONTH_NAME,SUM(PRICE_INR) AS MONTHLY_ORDER_TRENDS FROM FACT_SWIGGY_ORDERS F
JOIN DIM_DATE D ON D.DATE_ID=F.DATE_ID GROUP BY D.YEAR,D.MONTH,D.MONTH_NAME ORDER BY SUM(PRICE_INR) DESC

--QUATER TREND
SELECT D.YEAR,D.QUARTER,COUNT(*) AS QUARTER_ORDER_TRENDS FROM FACT_SWIGGY_ORDERS F
JOIN DIM_DATE D ON D.DATE_ID=F.DATE_ID GROUP BY D.YEAR,D.QUARTER ORDER BY COUNT(*) DESC

--YEARLY TREND
SELECT D.YEAR,COUNT(*) AS YEAR_ORDER_TRENDS FROM FACT_SWIGGY_ORDERS F
JOIN DIM_DATE D ON D.DATE_ID=F.DATE_ID GROUP BY D.YEAR ORDER BY COUNT(*) DESC

--ORDERS BY DAY OF WEEK (MON-SUN)
SELECT DATENAME(WEEKDAY,D.FULL_DATE) AS DAY_NAME,
COUNT(*) AS TOTAL_ORDERS FROM FACT_SWIGGY_ORDERS F 
JOIN DIM_DATE D ON F.DATE_ID=D.DATE_ID GROUP BY DATENAME(WEEKDAY,D.FULL_DATE) ORDER BY COUNT(*) DESC

--TOP 10 CITIES BY ORDER VOLUME.
SELECT TOP 10 L.CITY,COUNT(*) AS TOTAL_ORDERS FROM FACT_SWIGGY_ORDERS F
JOIN DIM_LOCATION L ON F.LOCATION_ID = L.LOCATION_ID GROUP BY L.CITY ORDER BY COUNT(*) DESC

--TOP 10 CITIES BY REVENUE
SELECT TOP 10 L.CITY,SUM(PRICE_INR) AS TOTAL_REVENUE FROM FACT_SWIGGY_ORDERS F
JOIN DIM_LOCATION L ON F.LOCATION_ID = L.LOCATION_ID GROUP BY L.CITY ORDER BY SUM(PRICE_INR) DESC

--REVENUE CONTRIBUTION BY STATES.
SELECT L.STATE,SUM(PRICE_INR) AS TOTAL_REVENUE_BY_STATE FROM FACT_SWIGGY_ORDERS F
JOIN DIM_LOCATION L ON F.LOCATION_ID = L.LOCATION_ID GROUP BY L.STATE ORDER BY SUM(PRICE_INR) DESC

--FOOD PERFORMANCE
--TOP 10 RESTAURANTS BY ORDERS
SELECT TOP 10 R.RESTAURANT_NAME,SUM(PRICE_INR) AS TOP_RESTAURANTS FROM FACT_SWIGGY_ORDERS F
JOIN DIM_RESTAURANT R ON R.RESTAURANT_ID=F.RESTAURANT_ID GROUP BY R.RESTAURANT_NAME ORDER BY SUM(PRICE_INR) DESC

--TOP 10 CATEGORIES
SELECT TOP 10 C.CATEGORY, COUNT(*) AS TOP_10_CATEGORIES FROM FACT_SWIGGY_ORDERS F
JOIN DIM_CATEGORY C ON C.CATEGORY_ID=F.CATEGORY_ID GROUP BY C.CATEGORY ORDER BY COUNT(*) DESC



--MOST ORDERED DISH 
SELECT TOP 1 DI.DISH_NAME,COUNT(*) AS MOST_ORDERED FROM FACT_SWIGGY_ORDERS F
JOIN DIM_DISH DI ON DI.DISH_ID=F.DISH_ID GROUP BY DI.DISH_NAME ORDER BY COUNT(*) DESC

--CUISINE PERFORMANCE --> ORDERS+AVG RATING
SELECT C.CATEGORY,COUNT(*) AS TOTAL_ORDERS,FORMAT(AVG(CONVERT(FLOAT,F.RATING)),'N2') AS AVG_RATING FROM FACT_SWIGGY_ORDERS F
JOIN DIM_CATEGORY C ON C.CATEGORY_ID=F.CATEGORY_ID GROUP BY C.CATEGORY ORDER BY COUNT(*) DESC

--CUSTOMER SPENDING INSIGHTS...
SELECT
CASE 
WHEN CONVERT(FLOAT,PRICE_INR)<100 THEN 'UNDER 100'
WHEN CONVERT(FLOAT,PRICE_INR) BETWEEN 100 AND 199 THEN '100 - 199'
WHEN CONVERT(FLOAT,PRICE_INR) BETWEEN 200 AND 299 THEN '200 - 299'
WHEN CONVERT(FLOAT,PRICE_INR) BETWEEN 300 AND 499 THEN '300 - 499'
ELSE '500+'
END AS PRICE_RANGE,
COUNT(*) AS TOTAL_ORDERS FROM FACT_SWIGGY_ORDERS
GROUP BY 
CASE 
WHEN CONVERT(FLOAT,PRICE_INR)<100 THEN 'UNDER 100'
WHEN CONVERT(FLOAT,PRICE_INR) BETWEEN 100 AND 199 THEN '100 - 199'
WHEN CONVERT(FLOAT,PRICE_INR) BETWEEN 200 AND 299 THEN '200 - 299'
WHEN CONVERT(FLOAT,PRICE_INR) BETWEEN 300 AND 499 THEN '300 - 499'
ELSE '500+'
END
ORDER BY TOTAL_ORDERS DESC

--RATING COUNT DISTRIBUTION(1 TO 5)
SELECT RATING,COUNT(*) AS RATING_COUNT FROM FACT_SWIGGY_ORDERS GROUP BY RATING ORDER BY COUNT(*) DESC


